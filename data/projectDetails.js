/**
 * Helper to find project by any recognized slug / alias / id
 */
export function getProjectBySlug(slug) {
  if (!slug) return null;
  const decoded = decodeURIComponent(slug).trim();
  
  // Direct ID match
  if (PROJECT_DETAILS[decoded]) return PROJECT_DETAILS[decoded];
  
  // Match across all projects
  for (const key of Object.keys(PROJECT_DETAILS)) {
    const p = PROJECT_DETAILS[key];
    if (p.id === decoded || p.canonicalSlug === decoded) return p;
    if (p.slugs && p.slugs.includes(decoded)) return p;
    // Check partial case-insensitive match
    if (decoded.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(decoded.toLowerCase())) {
      return p;
    }
  }
  return null;
}
